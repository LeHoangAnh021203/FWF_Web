export function isSiteLanguage(value: string | null | undefined): value is SiteLanguage {
  return Boolean(value && languageIds.has(value as SiteLanguage));
}

export function readStoredLanguage(): SiteLanguage {
  if (typeof window === "undefined") return "vi";
  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return isSiteLanguage(stored) ? stored : "vi";
}

export function applySiteLanguage(language: SiteLanguage) {
  if (typeof document === "undefined") return;
  const option = languageOptions.find((item) => item.id === language);
  document.documentElement.lang = option?.htmlLang ?? "vi";
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  window.dispatchEvent(new CustomEvent(LANGUAGE_CHANGE_EVENT, { detail: language }));
}

export function translate(language: SiteLanguage, key: string) {
  return (
    dictionaries[language][key] ??
    dictionaries.en[key] ??
    dictionaries.vi[key] ??
    key
  );
}
